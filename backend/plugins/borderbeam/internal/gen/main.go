// Generate the original WGSL shape and palette tables without rounding or retuning.
package main

import (
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

func main() {
	source, err := os.ReadFile("reference/beam-color.wgsl")
	if err != nil {
		panic(err)
	}
	arrays := regexp.MustCompile(`const (\w+) = array<vec4f, \d+>\(([^;]+)\);`)
	vectors := regexp.MustCompile(`vec4f\(([^)]+)\)`)
	var b strings.Builder
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n// Derived from Frad / Jakub Antalik border-beam; MIT, see reference/LICENSE.\npackage borderbeam\n\nvar referenceTables = map[string][]vector{\n")
	for _, m := range arrays.FindAllStringSubmatch(string(source), -1) {
		fmt.Fprintf(&b, "%q: {", m[1])
		for _, v := range vectors.FindAllStringSubmatch(m[2], -1) {
			fmt.Fprintf(&b, "{%s},", v[1])
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("tables_gen.go", out, 0644); err != nil {
		panic(err)
	}
}
